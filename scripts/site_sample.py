"""Data for the showcase site, from one synthetic match.

chain.js holds one real claim: the draft the Critic rejected and the rewrite that aired, with
every cited event resolved. match.js holds the match itself: totals and every shot.

    make site-data      # writes site/data/chain.js and site/data/match.js
"""

import argparse
import asyncio
import json
from pathlib import Path

from court.contracts import Cue, Output, RejectionNotice
from court.describe import describe
from court.localizer import Localizer
from court.metrics import shot_xg
from court.narrator import TemplateNarrator
from court.orchestrator import run_match
from court.state import MatchState
from match_events import Pass, Shot, generate, minute_label

DATA = Path(__file__).resolve().parents[1] / "site" / "data"


async def build(seed: int, overreach: float) -> dict:
    match = generate(seed)
    outputs: list[Output] = []
    narrator = TemplateNarrator(overreach_rate=overreach, seed=seed)
    await run_match(
        list(match.stream()),
        sink=outputs.append,
        narrator=narrator,
        localizer=Localizer(mode="analyst"),
    )

    first_drafts = {
        o.claim.alert_id: o
        for o in outputs
        if isinstance(o, RejectionNotice) and o.claim.attempt == 1
    }
    aired = next(
        o
        for o in outputs
        if isinstance(o, Cue)
        and o.status == "verified"
        and len(o.evidence) >= 2
        and o.alert_id in first_drafts
    )
    draft = first_drafts[aired.alert_id]

    by_id = {e.id: e for e in match.events}
    names = MatchState(match.meta)  # describes events with the players' names
    as_of = next(e.id for e in match.events if e.seq == draft.claim.as_of_seq)
    cited = sorted({*draft.claim.citations, *aired.evidence}, key=lambda i: by_id[i].seq)
    teams = (match.meta.home, match.meta.away)
    return {
        "source": f"synthetic match, seed {seed}; offline narrator overreach {overreach}",
        "teams": [{"name": t.name, "short": t.short_name, "color": t.color} for t in teams],
        "minute": aired.minute,
        "headline": aired.headline,
        "as_of": as_of,
        "draft": {
            "text": draft.claim.text,
            "citations": list(draft.claim.citations),
            "reasons": [{"code": r.code, "detail": r.detail} for r in draft.reasons],
        },
        "aired": {"text": aired.text, "evidence": list(aired.evidence), "attempts": aired.attempts},
        "events": [
            {
                "id": i,
                "minute": minute_label(by_id[i].t, by_id[i].period),
                "text": describe(by_id[i], names),
                "after_claim": by_id[i].seq > draft.claim.as_of_seq,
            }
            for i in cited
        ],
    }


def match_summary(seed: int) -> dict:
    match = generate(seed)
    names = {p.id: p.name for p in match.meta.players}
    shots = [e for e in match.events if isinstance(e, Shot)]

    def side(team, side_events: list[Shot]) -> dict:
        return {
            "name": team.name,
            "short": team.short_name,
            "goals": sum(s.outcome == "goal" for s in side_events),
            "shots": len(side_events),
            "xg": round(sum(shot_xg(s) for s in side_events), 2),
        }

    return {
        "seed": seed,
        "competition": match.meta.competition,
        "events": len(match.events),
        "passes": sum(isinstance(e, Pass) for e in match.events),
        "home": side(match.meta.home, [s for s in shots if s.team == "home"]),
        "away": side(match.meta.away, [s for s in shots if s.team == "away"]),
        # x and y are in the shooter's attacking direction: the goal is always at x = 105.
        "shots": [
            {
                "team": s.team.value,
                "minute": minute_label(s.t, s.period),
                "player": names[s.player_id],
                "x": round(s.x, 1),
                "y": round(s.y, 1),
                "xg": round(shot_xg(s), 2),
                "outcome": s.outcome.value,
            }
            for s in shots
        ],
    }


def write(name: str, var: str, data: dict) -> Path:
    path = DATA / name
    body = json.dumps(data, indent=2, ensure_ascii=False)
    path.parent.mkdir(parents=True, exist_ok=True)
    header = "// Generated by scripts/site_sample.py. Do not edit.\n"
    path.write_text(f"{header}window.{var} = {body};\n")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--overreach", type=float, default=0.25)
    args = parser.parse_args()
    chain = asyncio.run(build(args.seed, args.overreach))
    out = write("chain.js", "CHAIN", chain)
    print(f"wrote {out.relative_to(Path.cwd())}: {chain['minute']} {chain['headline']}")
    match = match_summary(args.seed)
    out = write("match.js", "MATCH", match)
    home, away = match["home"], match["away"]
    score = f"{home['short']} {home['goals']}-{away['goals']} {away['short']}"
    print(f"wrote {out.relative_to(Path.cwd())}: {score}, {len(match['shots'])} shots")


if __name__ == "__main__":
    main()
