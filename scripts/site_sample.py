"""Hero data for the showcase site: one real claim from a synthetic match, the draft the
Critic rejected and the rewrite that aired, with every cited event resolved.

    make site-data      # writes site/data/chain.js
"""

import argparse
import asyncio
import json
from pathlib import Path

from court.contracts import Cue, Output, RejectionNotice
from court.localizer import Localizer
from court.metrics import shot_distance, shot_xg
from court.narrator import TemplateNarrator
from court.orchestrator import run_match
from match_events import MatchEvent, Pass, Shot, generate, minute_label

OUT = Path(__file__).resolve().parents[1] / "site" / "data" / "chain.js"


def _describe(event: MatchEvent, names: dict[str, str]) -> str:
    match event:
        case Shot():
            where = "penalty" if event.situation == "penalty" else f"{shot_distance(event):.0f} m"
            outcome = event.outcome.replace("_", " ")
            return f"Shot by {names[event.player_id]}, {where}, {outcome}, xG {shot_xg(event):.2f}"
        case Pass():
            to = names[event.recipient_id]
            return f"Pass from {names[event.player_id]} to {to}, {event.distance_m:.0f} m"
        case _:
            reason = getattr(event, "reason", None)
            label = event.type.replace("_", " ").capitalize()
            return f"{label} ({reason.replace('_', ' ')})" if reason else label


async def build(seed: int, overreach: float) -> dict:
    match = generate(seed)
    outputs: list[Output] = []
    narrator = TemplateNarrator(overreach_rate=overreach, seed=seed)
    await run_match(
        list(match.stream()),
        sink=outputs.append,
        narrator=narrator,
        localizer=Localizer(mode="analyst"),
    )

    first_drafts = {
        o.claim.alert_id: o
        for o in outputs
        if isinstance(o, RejectionNotice) and o.claim.attempt == 1
    }
    aired = next(
        o
        for o in outputs
        if isinstance(o, Cue)
        and o.status == "verified"
        and len(o.evidence) >= 2
        and o.alert_id in first_drafts
    )
    draft = first_drafts[aired.alert_id]

    by_id = {e.id: e for e in match.events}
    names = {p.id: p.name for p in match.meta.players}
    as_of = next(e.id for e in match.events if e.seq == draft.claim.as_of_seq)
    cited = sorted({*draft.claim.citations, *aired.evidence}, key=lambda i: by_id[i].seq)
    teams = (match.meta.home, match.meta.away)
    return {
        "source": f"synthetic match, seed {seed}; offline narrator overreach {overreach}",
        "teams": [{"name": t.name, "short": t.short_name, "color": t.color} for t in teams],
        "minute": aired.minute,
        "headline": aired.headline,
        "as_of": as_of,
        "draft": {
            "text": draft.claim.text,
            "citations": list(draft.claim.citations),
            "reasons": [{"code": r.code, "detail": r.detail} for r in draft.reasons],
        },
        "aired": {"text": aired.text, "evidence": list(aired.evidence), "attempts": aired.attempts},
        "events": [
            {
                "id": i,
                "minute": minute_label(by_id[i].t, by_id[i].period),
                "text": _describe(by_id[i], names),
                "after_claim": by_id[i].seq > draft.claim.as_of_seq,
            }
            for i in cited
        ],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--overreach", type=float, default=0.25)
    args = parser.parse_args()
    chain = asyncio.run(build(args.seed, args.overreach))
    body = json.dumps(chain, indent=2, ensure_ascii=False)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = "// Generated by scripts/site_sample.py. Do not edit.\n"
    OUT.write_text(f"{header}window.CHAIN = {body};\n")
    print(f"wrote {OUT.relative_to(Path.cwd())}: {chain['minute']} {chain['headline']}")


if __name__ == "__main__":
    main()
